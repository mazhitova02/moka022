def paired_from_raw(pre, post):
    pre, post = np.asarray(pre, float), np.asarray(post, float)
    d = post - pre
    t = stats.ttest_rel(post, pre)
    dz = d.mean() / d.std(ddof=1)
    w = stats.wilcoxon(post, pre)
    print(f"    n={len(d)}  mean diff={d.mean():.2f}  s_d={d.std(ddof=1):.2f}  "
          f"t({len(d)-1})={t.statistic:.2f}  p={t.pvalue:.2g}  Cohen dz={dz:.2f}  "
          f"Wilcoxon p={w.pvalue:.2g}")
    return t

